import assert from 'node:assert/strict';
import {summarize,validAlert} from '../lib/risk.ts';
const now=Date.parse('2026-01-01T00:00:00Z');
const base=Array.from({length:49},(_,i)=>({startTime:new Date(now+i*3600000).toISOString(),endTime:new Date(now+(i+1)*3600000).toISOString(),temperature:25,temperatureUnit:'F',dewpoint:{value:-20},relativeHumidity:{value:40},probabilityOfPrecipitation:{value:0},shortForecast:'Clear',windSpeed:'10 mph',isDaytime:true}));
assert.equal(summarize(base,[],now).priority,0,'Dry cold is not ice');
assert.equal(summarize(base,[],now).hours.length,48,'Strict 48-hour cutoff');
assert.equal(summarize(base,[],now).complete,true);
const snow=structuredClone(base);snow[30].shortForecast='Chance Light Snow';snow[30].probabilityOfPrecipitation.value=40;
assert.equal(summarize(snow,[],now).priority,2);
assert.equal(summarize(snow,[],now,24).priority,0,'Snow after 24h must not leak into 24h view');
const ice=structuredClone(base);ice[2].shortForecast='Freezing Rain';assert.equal(summarize(ice,[],now).priority,3);
const frost=structuredClone(base);frost[4].relativeHumidity.value=95;assert(summarize(frost,[],now).hazards.includes('Frost risk'));
const wet=structuredClone(base);wet[1].shortForecast='Rain';wet[1].temperature=36;wet[1].probabilityOfPrecipitation.value=80;assert(summarize(wet,[],now).hazards.includes('Refreeze risk'));
const alert={status:'Actual',messageType:'Alert',event:'Ice Storm Warning',onset:new Date(now+3600000).toISOString(),expires:new Date(now+5*3600000).toISOString()};
assert.equal(summarize(base,[alert],now).priority,4);
assert.equal(validAlert({...alert,status:'Test'},now),false);
assert.equal(validAlert({...alert,expires:new Date(now-1).toISOString()},now),false);
assert.equal(validAlert({...alert,onset:new Date(now+49*3600000).toISOString(),expires:new Date(now+52*3600000).toISOString()},now),false);
const missing=structuredClone(base);missing[0].dewpoint.value=null;assert.equal(summarize(missing,[],now).complete,false);
console.log('Passed: dry cold, snow, ice, frost, refreeze, priority, horizon boundaries, expired/test alerts, incomplete data.');
const week=Array.from({length:169},(_,i)=>({...structuredClone(base[0]),startTime:new Date(now+i*3600000).toISOString(),endTime:new Date(now+(i+1)*3600000).toISOString()}));
week[60].shortForecast='Snow';week[120].shortForecast='Freezing Rain';week[168].shortForecast='Snow';
assert.equal(summarize(week,[],now,24).priority,0);
assert.equal(summarize(week,[],now,48).priority,0);
assert.equal(summarize(week,[],now,72).priority,2);
assert.equal(summarize(week,[],now,168).priority,3);
assert.equal(summarize(week,[],now,168).hours.length,168);
assert.equal(summarize(week,[],now,168).complete,true);
assert.equal(summarize(week.slice(0,140),[],now,168).complete,false);
assert.equal(summarize(week.slice(0,140),[],now,72).complete,true);
const lateAlert={...alert,onset:new Date(now+100*3600000).toISOString(),expires:new Date(now+150*3600000).toISOString()};
assert.equal(summarize(base,[lateAlert],now,72).priority,0);
assert.equal(summarize(week,[lateAlert],now,168).priority,4);
console.log('Passed: 24/48/72/168-hour priorities, late warning, exact week cutoff, and window-specific partial coverage.');
